#!/usr/bin/env python3
"""Regenerate public/sw.js: precache list + content-derived version.

Run before deploying:  python3 tools/build.py
Version changes only when the page or the media set changes, so clients
re-install the offline cache exactly when there is something new.
"""
import hashlib
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
IMG = PUBLIC / "img"
AUDIO = PUBLIC / "audio"
HTML = PUBLIC / "index.html"

images = sorted(p.name for p in IMG.glob("*.webp"))
clips = sorted(p.name for p in AUDIO.glob("*.mp3")) if AUDIO.exists() else []

h = hashlib.sha256()
h.update(HTML.read_bytes())
for name in images + clips:
    f = (IMG if name in images else AUDIO) / name
    h.update(name.encode())
    h.update(f.stat().st_size.to_bytes(8, "little"))
version = h.hexdigest()[:12]

listed = "\n".join(
    [f"  './img/{n}'," for n in images] + [f"  './audio/{n}'," for n in clips]
)

TEMPLATE = r"""/* generated by tools/build.py - do not edit by hand */
const VERSION = '__VERSION__';
const CACHE = 'atlas-' + VERSION;
const SHELL = './index.html';
const MEDIA = [
__MEDIA__
];

const OFFLINE = [
  '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
  '<title>Offline - Scope of Physics</title>',
  '<style>html,body{margin:0;height:100%;background:#dbd9d0;color:#183632;',
  'font-family:Arial,Helvetica,sans-serif;display:grid;place-items:center;text-align:center}',
  'h1{font:normal 2.1rem/1.1 Georgia,serif;letter-spacing:-.04em;margin:.3rem 0 .6rem}',
  'p{margin:0 0 1.4rem;color:#41574f;font:italic 1rem/1.5 Georgia,serif}',
  'button{padding:.7rem 1.4rem;border:0;border-radius:99px;background:#183632;color:#f4f0e5;',
  'font:600 .78rem/1 monospace;letter-spacing:.14em;text-transform:uppercase;cursor:pointer}',
  '</style><main><h1>You are offline</h1>',
  '<p>The deck is saved on this device, but this page was not cached yet.</p>',
  '<button onclick="location.reload()">Try again</button></main>',
].join('');

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    try {
      await cache.addAll(['./', SHELL].map((u) => new Request(u, { cache: 'reload' })));
    } catch (e) {}
    await Promise.allSettled(
      MEDIA.map((u) => cache.add(new Request(u, { cache: 'reload' })).catch(() => {})),
    );
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

async function shellFrom(cache, request) {
  return (
    (await cache.match(SHELL)) ||
    (await cache.match('./')) ||
    (await cache.match(request)) ||
    null
  );
}

async function refreshShell() {
  try {
    const fresh = await fetch(SHELL, { cache: 'no-cache' });
    if (!fresh || !fresh.ok) return;
    const cache = await caches.open(CACHE);
    const held = await cache.match(SHELL);
    if (!held) {
      await cache.put(SHELL, fresh.clone());
      return;
    }
    const [next, now] = await Promise.all([fresh.clone().text(), held.clone().text()]);
    if (next !== now) await cache.put(SHELL, fresh.clone());
  } catch (e) {}
}

async function navigate(request) {
  let held = null;
  try {
    held = await shellFrom(await caches.open(CACHE), request);
  } catch (e) {}
  if (held) return held;
  try {
    return await fetch(request);
  } catch (e) {}
  try {
    const again = await shellFrom(await caches.open(CACHE), request);
    if (again) return again;
  } catch (e) {}
  return new Response(OFFLINE, {
    status: 200,
    headers: { 'content-type': 'text/html; charset=utf-8' },
  });
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  let url;
  try {
    url = new URL(request.url);
  } catch (e) {
    return;
  }
  if (url.origin !== self.location.origin) return;
  if (url.pathname.endsWith('/sw.js')) return;

  if (request.mode === 'navigate') {
    event.respondWith(navigate(request));
    event.waitUntil(refreshShell());
    return;
  }

  event.respondWith((async () => {
    try {
      const cache = await caches.open(CACHE);
      const held = await cache.match(request);
      if (held) return held;
      const response = await fetch(request);
      if (response && response.ok && response.type === 'basic') {
        cache.put(request, response.clone());
      }
      return response;
    } catch (e) {
      try {
        const cache = await caches.open(CACHE);
        const held = await cache.match(request, { ignoreSearch: true });
        if (held) return held;
      } catch (err) {}
      return new Response('', { status: 504, statusText: 'Offline' });
    }
  })());
});
"""

(PUBLIC / "sw.js").write_text(
    TEMPLATE.replace("__VERSION__", version).replace("__MEDIA__", listed),
    encoding="utf-8",
)
print(f"sw.js written: version {version}, {len(images)} images, {len(clips)} clips")

cover = re.search(r'src="\./img/([^"]+)"', HTML.read_text(encoding="utf-8"))
if cover:
    print(f"cover image: {cover.group(1)}")
