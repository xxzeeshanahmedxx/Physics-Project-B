#!/usr/bin/env python3
"""Regenerate public/sw.js: precache list + content-derived version.

Run before deploying:  python3 tools/build.py
Version changes only when the page or the image set changes, so clients
re-install the offline cache exactly when there is something new.
"""
import hashlib
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
IMG = PUBLIC / "img"
HTML = PUBLIC / "index.html"

images = sorted(p.name for p in IMG.glob("*.webp"))

h = hashlib.sha256()
h.update(HTML.read_bytes())
for name in images:
    h.update(name.encode())
    h.update((IMG / name).stat().st_size.to_bytes(8, "little"))
version = h.hexdigest()[:12]

listed = "\n".join(f"  './img/{n}'," for n in images)

sw = f"""/* generated by tools/build.py - do not edit by hand */
const VERSION = '{version}';
const CACHE = 'atlas-' + VERSION;
const SHELL = './index.html';
const ART = [
{listed}
];

self.addEventListener('install', (event) => {{
  event.waitUntil((async () => {{
    const cache = await caches.open(CACHE);
    await cache.addAll(['./', SHELL].map((u) => new Request(u, {{ cache: 'reload' }})));
    await Promise.allSettled(
      ART.map((u) => cache.add(new Request(u, {{ cache: 'reload' }})).catch(() => {{}})),
    );
    await self.skipWaiting();
  }})());
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil((async () => {{
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  }})());
}});

async function revalidate(cache, request) {{
  try {{
    const fresh = await fetch(request.url, {{ cache: 'no-cache' }});
    if (!fresh.ok) return;
    const held = await cache.match(SHELL);
    if (!held) {{
      await cache.put(SHELL, fresh.clone());
      return;
    }}
    const [next, now] = await Promise.all([fresh.clone().text(), held.clone().text()]);
    if (next !== now) await cache.put(SHELL, fresh.clone());
  }} catch (e) {{}}
}}

self.addEventListener('fetch', (event) => {{
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.endsWith('/sw.js')) return;

  if (request.mode === 'navigate') {{
    event.respondWith((async () => {{
      const cache = await caches.open(CACHE);
      const held = (await cache.match(SHELL)) || (await cache.match(request));
      event.waitUntil(revalidate(cache, request));
      return held || fetch(request);
    }})());
    return;
  }}

  event.respondWith((async () => {{
    const cache = await caches.open(CACHE);
    const held = await cache.match(request);
    if (held) return held;
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') cache.put(request, response.clone());
    return response;
  }})());
}});
"""

(PUBLIC / "sw.js").write_text(sw, encoding="utf-8")
print(f"sw.js written: version {version}, {len(images)} images")

# keep the page's preload hint on the current cover image
cover = re.search(r'src="\./img/([^"]+)"', HTML.read_text(encoding="utf-8"))
if cover:
    print(f"cover image: {cover.group(1)}")
